#include <iostream>
#include <cstdlib>
#include <ctime>
#include <clocale>
using namespace std;

int main()
{
    const int N = 100;
    int a[N];               // память под 100 элементов

    int n;                  // длина массива
    int i, j, t;

    setlocale(LC_ALL, "");  
    srand(time(NULL));      // настройка датчика случайных чисел

    // ----- 1. Формирование массива датчиком случайных чисел -----
    do
    {
        cout << "Введите длину массива (13..100): ";
        cin >> n;
    } while (n < 13 || n > N);          // реальная длина не больше N

    for (i = 0; i < n; i++)
        a[i] = rand() % 101 - 50;       // числа от -50 до 50

    // Печать полученного массива
    cout << "\nИсходный массив (" << n << " элементов):\n";
    for (i = 0; i < n; i++)
        cout << a[i] << "  ";
    cout << endl;

    // Переворот массива
    for (i = 0, j = n - 1; i < j; i++, j--)
    {
        t    = a[i];
        a[i] = a[j];
        a[j] = t;
    }

    // если число элементов нечётное — удалить средний
    if (n % 2 == 1)
    {
        // Методические указания: при уменьшении длины изменяем длину массива
        for (i = n / 2; i < n - 1; i++)
            a[i] = a[i + 1];            // сдвиг влево от среднего
        n--;
    }

    cout << "\nМассив после переворота (" << n << " элементов):\n";
    for (i = 0; i < n; i++)
        cout << a[i] << "  ";
    cout << endl;

    // Добавить в начало 3 элемента со значением M[I+10]-2
    int newel[3];
    for (i = 0; i < 3; i++)
        newel[i] = a[i + 10] - 2;       // запоминаем значения ДО сдвига

    // Методические указания, п.2: при увеличении длины
    // изменяем реальную длину массива
    for (i = n - 1; i >= 0; i--)
        a[i + 3] = a[i];                // сдвиг вправо с конца массива
    n += 3;

    for (i = 0; i < 3; i++)
        a[i] = newel[i];                // вставка новых элементов в начало

    // Печать полученного массива
    cout << "\nИтоговый массив (" << n << " элементов):\n";
    for (i = 0; i < n; i++)
        cout << a[i] << "  ";
    cout << endl;

    return 0;
}
